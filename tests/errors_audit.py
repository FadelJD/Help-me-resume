"""Error-message audit: run every bad fixture through the CLI and capture what it prints.

    python -m tests.errors_audit            # print the table
    python -m tests.errors_audit --write    # also write docs/errors.md

Every error line must name where (a file path, or the command for argument errors), a line
number or item id, and a one-line fix. tests/test_errors.py enforces it and keeps the doc current.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import re
import shlex
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from cvforge.cli import main

ROOT = Path(__file__).resolve().parent.parent
BAD = ROOT / "tests" / "fixtures" / "bad"
DOC = ROOT / "docs" / "errors.md"

# where[:line] [item]: severity: message Fix: fix
LINE = re.compile(
    r"^(?P<where>\S[^\[]*?)(?::(?P<line>\d+))?(?: \[(?P<item>[^\]]+)\])?: "
    r"(?P<severity>error|warning): (?P<message>.+?) Fix: (?P<fix>\S.*)$"
)


@dataclass(frozen=True)
class Case:
    kind: str  # profile | hat | template | command
    name: str
    argv: list[str]
    target: str  # what the message must name: the fixture path, or the command


@dataclass(frozen=True)
class Outcome:
    case: Case
    exit_code: int
    lines: list[str]


def cases(tmp: Path) -> list[Case]:
    out: list[Case] = []
    for f in sorted((BAD / "profile").glob("*.cv.txt")):
        rel = str(f.relative_to(ROOT))
        out.append(Case("profile", f.name.removesuffix(".cv.txt"), ["validate", "-p", rel], rel))
    for f in sorted((BAD / "hat").glob("*.toml")):
        rel = str(f.relative_to(ROOT))
        argv = ["build", "-p", "examples/profile.cv.txt", "-t", "templates/minimal.tex"]
        out.append(Case("hat", f.stem, [*argv, "--hat", rel], rel))
    for f in sorted((BAD / "template").glob("*.tex")):
        rel = str(f.relative_to(ROOT))
        out.append(Case("template", f.stem, ["template", "validate", rel], rel))
    for raw in (BAD / "commands.txt").read_text().splitlines():
        if not raw.strip() or raw.startswith("#"):
            continue
        argv = [a.replace("{tmp}", str(tmp)) for a in shlex.split(raw)]
        out.append(Case("command", raw.replace("{tmp}", "<copy of profile>"), argv, ""))
    return out


def run_case(case: Case) -> Outcome:
    err = io.StringIO()
    with contextlib.redirect_stderr(err), contextlib.redirect_stdout(io.StringIO()):
        code = main(case.argv)
    lines = [ln for ln in err.getvalue().splitlines() if ": error: " in ln]
    return Outcome(case, code, lines)


def run_all() -> list[Outcome]:
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d) / "profile.cv.txt"
        shutil.copy(ROOT / "examples" / "profile.cv.txt", tmp)
        results = []
        for case in cases(tmp):
            shutil.copy(ROOT / "examples" / "profile.cv.txt", tmp)
            r = run_case(case)
            masked = [ln.replace(d, "<tmp>") for ln in r.lines]
            results.append(Outcome(r.case, r.exit_code, masked))
        return results


def document(results: list[Outcome]) -> str:
    rows = [
        "# Error messages",
        "",
        "Every bad fixture in `tests/fixtures/bad/` run through the CLI, with the first error it",
        "prints. Each message names where (the file, or for argument errors the command), a line",
        "number or item id in square brackets, and a one-line fix. Generated by",
        "`python -m tests.errors_audit --write`; `tests/test_errors.py` checks every line.",
        "",
        "| Kind | Fixture or command | Message |",
        "| --- | --- | --- |",
    ]
    for r in results:
        name = r.case.name.replace("|", "\\|")
        first = (r.lines[0] if r.lines else "(no error printed)").replace("|", "\\|")
        rows.append(f"| {r.case.kind} | `{name}` | `{first}` |")
    return "\n".join(rows) + "\n"


def main_cli() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    results = run_all()
    text = document(results)
    if args.write:
        DOC.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main_cli()
